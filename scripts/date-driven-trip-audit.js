'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const M=require('../trip-itinerary.js');
const parks=[{slug:'rice',name:'Rice Lake',city:'Owatonna',state:'MN'},{slug:'afton',name:'Afton',city:'Hastings',state:'MN'},{slug:'crosby',name:'George H. Crosby Manitou',city:'Silver Bay',state:'MN'}];
const t={startDate:'2026-10-31',endDate:'2026-11-07',calendarDays:true,dayCount:0,parks:parks.map(x=>x.slug),stopMeta:{rice:{day:'',camping:true,campground:'Rice Lake',loop:'B',campsite:'12',reservation:'R123',checkIn:'15:00',checkOut:'11:00'},afton:{day:''},crosby:{day:''}}};
assert.equal(M.dateRangeDays(t),8);
assert.equal(M.ensureDayCount(t),8);
let days=M.build(t,parks,{}).days;
assert.equal(days.length,9);
assert.deepEqual(days.slice(0,8).map(d=>d.date),['2026-10-31','2026-11-01','2026-11-02','2026-11-03','2026-11-04','2026-11-05','2026-11-06','2026-11-07']);
assert.equal(days.at(-1).key,'Unassigned');
assert.equal(days.at(-1).stopCount,3);
assert.equal(M.addDayToTrip(t),false);
assert.equal(M.removeDayFromTrip(t,1),false);
assert.equal(M.moveDayInTrip(t,2,-1),false);
t.stopMeta.rice.day='4';
days=M.build(t,parks,{}).days;
assert.equal(days[3].stops[0].meta.reservation,'R123');
assert.equal(days[3].stops[0].meta.campground,'Rice Lake');
t.endDate='2026-11-02';
assert.equal(M.ensureDayCount(t),3);
assert.equal(t.stopMeta.rice.day,'4','out-of-range assignment must not be erased');
assert.equal(M.build(t,parks,{}).days.at(-1).stops.some(s=>s.slug==='rice'),true,'out-of-range assignment must surface for review');
assert.equal(M.dateRangeDays({...t,endDate:'2026-10-30'}),0);
const legacy={dayCount:2,startDate:'2026-10-31',parks:[],stopMeta:{}};
assert.equal(M.addDayToTrip(legacy),3);
assert.equal(M.removeDayFromTrip(legacy,2),true);
const build=fs.readFileSync(require('node:path').join(__dirname,'build-cloudflare.js'),'utf8');
const editor=fs.readFileSync(require('node:path').join(__dirname,'../trip-day-editor.js'),'utf8');
const sync=fs.readFileSync(require('node:path').join(__dirname,'../trip-logistics-sync-v119.js'),'utf8');
assert(editor.includes('Your \'+count+\' days come from the saved trip dates.'));
assert(editor.includes('calendar?'));
assert(sync.includes('trip.calendarDays=true'));
assert(build.includes('Canonical trip day editor missing, duplicated, or out of load order'));
console.log('PASS: Eight calendar day slots, explicit assignments, campsite preservation, shortened-range review, manual fallback, and editor wiring.');
